export const topicsByChapter = Object.fromEntries(
  Object.values(syllabus).flatMap(units => units.map(unit => [unit.chapter, unit.topics])),
) as Record<string, readonly string[]>;

import canonicalTaxonomyData from './canonical-taxonomy.json';

export interface CanonicalChapter {
  id: number;
  unit_code: string;
  chapter_name: string;
  chapter_slug: string;
  subject: string;
  chapter_number: number;
  total_topics: number;
  eligible_question_count: number;
  topics: CanonicalTopic[];
}

export interface CanonicalTopic {
  id: number;
  topic_code: string;
  topic_name: string;
  topic_number: number;
  unit_code: string;
  subject: string;
  eligible_question_count: number;
}

export const CANONICAL_TAXONOMY: Record<string, CanonicalChapter[]> = canonicalTaxonomyData as any;

export function getDefaultChapters(subject: string = 'Physics'): CanonicalChapter[] {
  const norm = subject.charAt(0).toUpperCase() + subject.slice(1).toLowerCase();
  return CANONICAL_TAXONOMY[norm] || CANONICAL_TAXONOMY['Physics'] || [];
}

export function getDefaultTopics(chapterCode: string = 'PHYS_U01'): CanonicalTopic[] {
  for (const list of Object.values(CANONICAL_TAXONOMY)) {
    const found = list.find((c) => c.unit_code === chapterCode || c.chapter_name === chapterCode);
    if (found) return found.topics;
  }
  return CANONICAL_TAXONOMY['Physics']?.[0]?.topics || [];
}

